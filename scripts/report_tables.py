"""Builds report/results_tables.md: every number for the report, read from the saved result files.
Copy tables from here into the PDF so each value is traceable to a CSV in the repository.
Usage:  python -m scripts.report_tables"""
import json
import pandas as pd

from src.config import OUT_DIR, ROOT, FINAL_MODEL
from src.models import MODEL_SPECS

NAMES = {"gaussian_nb": "Gaussian Naive Bayes", "logistic_regression": "Logistic Regression",
         "random_forest": "Random Forest", "hist_gradient_boosting": "HistGradientBoosting", "mlp": "MLP",
         "hist_gradient_boosting_tuned": "HistGradientBoosting (tuned)"}


def f(x, d=4):
    return "N/A" if pd.isna(x) else f"{x:.{d}f}"


def num(v, kind):
    return f"{int(round(v))}" if kind == "int" else f"{v:.4g}"


def table(df):
    cols = list(df.columns)
    lines = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    lines += ["| " + " | ".join(str(v) for v in r) + " |" for r in df.itertuples(index=False)]
    return "\n".join(lines)


def main():
    exp, hmm, tun = OUT_DIR / "experiments", OUT_DIR / "hmm", OUT_DIR / "tuning"
    res = pd.read_csv(exp / "model_comparison.csv")
    folds = pd.read_csv(exp / "cv_folds.csv")
    allh = pd.read_csv(hmm / "all_models_classifier_vs_hmm.csv").set_index("model")
    # rows ordered by the selection metric: student-test top-1 after HMM
    res = res.assign(_k=res.model.map(allh.hmm_top1)).sort_values("_k", ascending=False).drop(columns="_k")
    md = ["# PathSnap - results tables (auto-generated by scripts/report_tables.py)\n",
          "Every value is read from files in `outputs/`. Re-run the script after re-running experiments.\n"]

    # 3.1 consolidated comparison - exactly the columns the guideline asks for
    rows = []
    for r in res.itertuples():
        h = allh.loc[r.model] if r.model in allh.index else None
        rows.append([NAMES[r.model], r.family, r.config,
                     f"{r.cv_f1_macro_mean:.4f} ± {r.cv_f1_macro_std:.4f}",
                     f"{r.test_top1_accuracy:.4f} (+HMM {h.hmm_top1:.4f})" if h is not None else f(r.test_top1_accuracy),
                     f"{r.test_route_continuity:.4f} (+HMM {h.hmm_continuity:.4f})" if h is not None else f(r.test_route_continuity),
                     f(r.test_f1_macro), f(r.test_log_loss), f"{r.inference_time_s:.3f} s"])
    md += ["## 3.1 Overall model comparison (student-test unless stated)\n",
           table(pd.DataFrame(rows, columns=["Model", "Algorithm family", "Key configuration", "CV macro F1 (5-fold, mean ± std)",
                                             "Top-1 accuracy", "Route continuity", "Student-test macro F1", "Log loss",
                                             "Inference time (164,601 candidate rows)"])),
           "\nRows are ordered by the selection metric (top-1 after HMM). CV = 5-fold GroupKFold over the 78 usable training trips. Top-1 / continuity: classifier only, "
           "then after HMM/Viterbi (beta = 2 m). Log loss is applicable to all five (all output probabilities).\n"]

    # 3.2 per-model detail
    md.append("## 3.2 Per-model detail (for the compulsory questions)\n")
    for r in res.itertuples():
        g = folds[folds.model == r.model]
        spec = MODEL_SPECS[r.model]
        md += [f"### {NAMES[r.model]}\n",
               table(pd.DataFrame([
                   ["Initial hyperparameters", spec["config"]],
                   ["Loss / optimisation objective", spec["objective"]],
                   ["Training rows used (sampled)", f"{int(r.train_rows_used):,}"],
                   ["Fit time (full refit)", f"{r.fit_time_s:.1f} s"],
                   ["Macro F1: train folds vs validation folds", f"{g.train_f1_macro.mean():.4f} vs {g.f1_macro.mean():.4f} (gap {g.train_f1_macro.mean() - g.f1_macro.mean():+.4f})"],
                   ["Log loss: train folds vs validation folds", f"{g.train_log_loss.mean():.4f} vs {g.log_loss.mean():.4f}"],
                   ["Top-1: train folds vs validation folds", f"{g.train_top1_accuracy.mean():.4f} vs {g.top1_accuracy.mean():.4f}"],
                   ["Per-fold validation macro F1", ", ".join(f"{v:.3f}" for v in g.f1_macro)],
                   ["Student-test accuracy / precision / recall (macro)", f"{r.test_accuracy:.4f} / {r.test_precision_macro:.4f} / {r.test_recall_macro:.4f}"],
                   ["Student-test macro F1 / log loss", f"{r.test_f1_macro:.4f} / {r.test_log_loss:.4f}"],
                   ["Student-test top-1 (classifier / +HMM)", f"{r.test_top1_accuracy:.4f} / {allh.loc[r.model].hmm_top1:.4f}" if r.model in allh.index else f(r.test_top1_accuracy)],
                   ["Candidate miss rate", f"{r.test_candidate_miss_rate:.4f}"],
                   ["Epoch-wise training curve", "Yes: outputs/experiments/mlp_loss_curve.csv" if r.model == "mlp" else "N/A: not trained in epochs"],
               ], columns=["Item", "Value"])), ""]

    # 4 Bayesian optimisation
    if (tun / "tuned_vs_untuned.csv").exists():
        best = json.loads((tun / "best_params.json").read_text())
        space = json.loads((tun / "search_space.json").read_text())
        tv = pd.read_csv(tun / "tuned_vs_untuned.csv")
        md += ["## 4 Bayesian hyperparameter optimisation (HistGradientBoosting)\n",
               table(pd.DataFrame([[k, v["type"], num(v["low"], v["type"]), num(v["high"], v["type"]),
                                    "log" if v["log_scale"] else "uniform", num(best["params"][k], v["type"])]
                                   for k, v in space.items() if not k.startswith("_")],
                                  columns=["Hyperparameter", "Type", "Low", "High", "Prior", "Best value"])),
               f"\nSampler: {space['_sampler']}. Objective: {space['_objective']}. Fixed: {space['_fixed']}. "
               f"Trials: {best['n_trials']}, best trial #{best['best_trial']} (CV top-1 {best['best_cv_top1']:.4f}). "
               f"Tuning cost: {best['tuning_time_s']:.0f} s.\n",
               table(pd.DataFrame([[r.model, f"{r.cv_f1_macro_mean:.4f} ± {r.cv_f1_macro_std:.4f}", f(r.test_top1_accuracy),
                                    f(r.test_f1_macro), f(r.test_log_loss), f"{r.inference_time_s:.3f} s", f"{r.fit_time_s:.1f} s",
                                    int(r.n_iter_used)] for r in tv.itertuples()],
                                  columns=["Model", "CV macro F1", "Student-test top-1", "Student-test macro F1",
                                           "Log loss", "Inference time", "Fit time", "Boosting rounds used"])), ""]

    # 5 HMM
    sweep_file = hmm / f"hmm_vs_classifier_{FINAL_MODEL}.csv"
    if not sweep_file.exists():
        sweep_file = hmm / "hmm_vs_classifier_hist_gradient_boosting.csv"
    sw = pd.read_csv(sweep_file)
    md += [f"## 5 HMM / Viterbi\n", f"### Beta sweep ({NAMES[sw.model.iloc[0]]}, student-test)\n",
           table(pd.DataFrame([[f"{r.beta:g}", f(r.clf_top1_accuracy), f(r.hmm_top1_accuracy), f(r.clf_route_continuity),
                                f(r.hmm_route_continuity), f"{r.decode_time_s:.1f} s"] for r in sw.itertuples()],
                              columns=["beta (m)", "Top-1 classifier", "Top-1 +HMM", "Continuity classifier",
                                       "Continuity +HMM", "Decode time (10 trips)"])), ""]
    allh2 = pd.read_csv(hmm / "all_models_classifier_vs_hmm.csv").sort_values("hmm_top1", ascending=False)
    md += ["### Every model through the same decoder\n",
           table(pd.DataFrame([[NAMES.get(r.model, r.model), f(r.classifier_top1), f(r.hmm_top1),
                                f"{(r.hmm_top1 - r.classifier_top1) * 100:+.2f} pts", f(r.classifier_continuity),
                                f(r.hmm_continuity)] for r in allh2.itertuples()],
                              columns=["Model", "Top-1 classifier", "Top-1 +HMM", "Gain", "Continuity classifier",
                                       "Continuity +HMM"])), ""]
    pt_file = hmm / f"per_trip_{sw.model.iloc[0]}.csv"
    pt = pd.read_csv(pt_file, dtype={"trip": str})
    md += [f"### Per student-test trip ({NAMES[sw.model.iloc[0]]}, beta = {pt.beta.iloc[0]:g})\n",
           table(pd.DataFrame([[r.trip, r.n_pts, f(r.clf_top1), f(r.hmm_top1), f"{(r.hmm_top1 - r.clf_top1) * 100:+.2f}",
                                f(r.clf_route_f1), f(r.hmm_route_f1)] for r in pt.itertuples()],
                              columns=["Trip", "Points", "Top-1 classifier", "Top-1 +HMM", "Gain (pts)",
                                       "Route F1 classifier", "Route F1 +HMM"])), ""]

    # 7 API
    sm = OUT_DIR / "api_logs" / "api_smoke_test.csv"
    if sm.exists():
        s = pd.read_csv(sm, dtype={"trip_id": str})
        md += ["## 7 API end-to-end check (every trip through POST /predict)\n",
               table(pd.DataFrame([[r.trip_id, r.status, r.n_points, f(r.classifier_top1), f(r.hmm_top1),
                                    f(r.hmm_continuity), f"{r.api_compute_s:.2f} s"] for r in s.itertuples()],
                                  columns=["Trip", "HTTP", "Points", "Top-1 classifier", "Top-1 +HMM",
                                           "Continuity +HMM", "API compute time"])), ""]

    out = ROOT / "report" / "results_tables.md"; out.parent.mkdir(exist_ok=True)
    out.write_text("\n".join(md))
    print("written", out)


if __name__ == "__main__":
    main()
